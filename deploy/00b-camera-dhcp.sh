#!/usr/bin/env bash
# Phase 00b — Camera-NIC DHCP server (dnsmasq)
# Hands out 10.42.0.10–250 to cameras on the camera NIC.
# DNS disabled (cameras don't need it); listens only on the camera interface.

set -euo pipefail
DEPLOY_DIR="$(cd "$(dirname "$0")" && pwd)"
source "$DEPLOY_DIR/config.sh"

CAM_RANGE_START="${CAM_RANGE_START:-10.42.0.10}"
CAM_RANGE_END="${CAM_RANGE_END:-10.42.0.250}"

echo "[00b-camera-dhcp] Installing dnsmasq for camera NIC: $CAM_NIC"
echo "  Lease range: $CAM_RANGE_START — $CAM_RANGE_END"

DEBIAN_FRONTEND=noninteractive apt-get install -y -qq dnsmasq

# Drop-in config — DHCP only, on the camera NIC, no DNS
cat > /etc/dnsmasq.d/aurasense-cameras.conf << CONF
# AuraSense camera DHCP — generated by deploy/00b-camera-dhcp.sh
interface=$CAM_NIC
bind-interfaces
no-resolv
port=0
dhcp-range=$CAM_RANGE_START,$CAM_RANGE_END,24h
dhcp-option=option:router,$CAMERA_NIC_IP
log-dhcp
CONF

# UFW: allow DHCP (UDP 67) inbound on camera NIC
if command -v ufw >/dev/null 2>&1 && ufw status | grep -q "Status: active"; then
    ufw allow in on "$CAM_NIC" to any port 67 proto udp comment 'DHCP (cameras)' || true
fi

systemctl enable --now dnsmasq
systemctl restart dnsmasq

sleep 2
if systemctl is-active --quiet dnsmasq; then
    echo "[00b-camera-dhcp] dnsmasq running."
    echo "  Cameras set to DHCP will pick up an IP within ~30 s, or after a power cycle."
else
    echo "[00b-camera-dhcp] WARNING: dnsmasq is not active. Check: journalctl -u dnsmasq -n 30"
    exit 1
fi

echo ""
echo "[00b-camera-dhcp] Done."
